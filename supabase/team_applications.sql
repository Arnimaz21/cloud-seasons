-- Team applications for Cloud.Seasons (/team/).
-- Run this once in Supabase Dashboard -> SQL Editor before publishing the page.

create table if not exists public.team_applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  discord text not null,
  telegram text,
  name text not null,
  age integer not null,
  timezone text not null,
  minecraft_years text not null,
  weekly_hours text not null,
  roles text not null,
  custom_role text,
  motivation text not null,
  agreed_rules boolean not null default false,
  agreed_data boolean not null default false,
  status text not null default 'new'
);

alter table public.team_applications enable row level security;

-- The public site may only insert new applications.
drop policy if exists "team_applications_insert_anon" on public.team_applications;
create policy "team_applications_insert_anon"
  on public.team_applications
  for insert
  to anon
  with check (true);

-- Only signed-in administrators may read applications.
drop policy if exists "team_applications_select_admin" on public.team_applications;
create policy "team_applications_select_admin"
  on public.team_applications
  for select
  to authenticated
  using (true);

grant insert on public.team_applications to anon;
grant select on public.team_applications to authenticated;
grant usage, select on sequence public.team_applications_id_seq to anon;
